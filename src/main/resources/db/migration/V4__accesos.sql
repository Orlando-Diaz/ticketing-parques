-- Modulo accesos: un pase (un QR) por orden, con el historial de ingresos por la puerta.
-- No hay llave foranea hacia orden/parque: cada modulo es dueno de sus tablas y se hablan por eventos.
create table pase (
    id               varchar(100) primary key,
    codigo           varchar(64)  not null unique,   -- lo que lleva el QR; imposible de adivinar
    orden_ref        varchar(100) not null unique,   -- una orden, un pase (protege contra eventos repetidos)
    parque_id        varchar(100) not null,
    fecha_visita     date         not null,
    entradas_totales integer      not null check (entradas_totales >= 1),
    entradas_usadas  integer      not null check (entradas_usadas >= 0),
    estado           varchar(20)  not null,
    emitido_en       timestamp    not null,
    version          bigint       not null default 0, -- bloqueo optimista (ver docs/adr/0004)
    -- ultima linea de defensa: ni un bug en la aplicacion puede dejar entrar a mas personas que las compradas
    constraint ck_usadas_dentro_de_lo_comprado check (entradas_usadas <= entradas_totales)
);

create table ingreso (
    id        bigint generated by default as identity primary key,
    pase_id   varchar(100) not null references pase (id),
    posicion  integer      not null,
    personas  integer      not null check (personas >= 1),
    puerta    varchar(100) not null,
    momento   timestamp    not null
);
