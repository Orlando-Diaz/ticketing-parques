-- Cada modulo es dueno de sus tablas. Entre modulos NO hay llaves foraneas
-- (se hablan por la aplicacion, no por la base de datos), para poder separarlos mas adelante.

-- ===== catalogo =====
create table parque (
    id          varchar(100) primary key,
    nombre      varchar(200) not null,
    cupo_diario integer      not null check (cupo_diario >= 1)
);

create table disponibilidad_diaria (
    parque_id   varchar(100) not null references parque (id),
    fecha       date         not null,
    cupo_maximo integer      not null check (cupo_maximo >= 0),
    vendidas    integer      not null check (vendidas >= 0),
    primary key (parque_id, fecha),
    -- ultima linea de defensa: ni un bug en la aplicacion puede dejar mas vendidas que el cupo
    constraint ck_vendidas_dentro_del_cupo check (vendidas <= cupo_maximo)
);

-- ===== precios =====
create table configuracion_precios (
    parque_id    varchar(100) primary key,
    esquema_tipo varchar(30)  not null,
    precio_unico bigint
);

create table categoria_tarifa (
    id          bigint generated by default as identity primary key,
    parque_id   varchar(100) not null references configuracion_precios (parque_id),
    posicion    integer      not null,
    nombre      varchar(100) not null,
    edad_minima integer      not null,
    edad_maxima integer,
    precio      bigint       not null
);

create table regla_precio (
    id            bigint generated by default as identity primary key,
    parque_id     varchar(100) not null references configuracion_precios (parque_id),
    posicion      integer      not null,
    tipo          varchar(40)  not null,
    porcentaje    integer,
    tamano_minimo integer
);

-- ===== ventas =====
create table orden (
    id           varchar(100) primary key,
    parque_id    varchar(100) not null,
    fecha_visita date         not null,
    creada_en    timestamp    not null,
    total        bigint       not null,
    estado       varchar(20)  not null
);

create table linea_orden (
    id             bigint generated by default as identity primary key,
    orden_id       varchar(100) not null references orden (id),
    posicion       integer      not null,
    edad_visitante integer      not null,
    residente      boolean      not null,
    precio         bigint       not null
);

-- ===== facturacion =====
create table consecutivo (
    id     varchar(50) primary key,
    ultimo bigint      not null
);
insert into consecutivo (id, ultimo) values ('FACTURA', 0);

create table factura (
    id         varchar(100) primary key,
    numero     varchar(30)  not null unique,
    orden_ref  varchar(100) not null unique,  -- una orden, una factura (protege contra eventos repetidos)
    parque_id  varchar(100) not null,
    total      bigint       not null,
    emitida_en timestamp    not null,
    estado     varchar(20)  not null
);

create table linea_factura (
    id          bigint generated by default as identity primary key,
    factura_id  varchar(100) not null references factura (id),
    posicion    integer      not null,
    descripcion varchar(300) not null,
    valor       bigint       not null
);
